def ring(opt, static):
    N['n'] += 1
    u = 'u%d' % N['n']
    if opt == 'aperture':
        inner = ''.join('<path class="seg s%d" d="%s"/>' % (i, d)
                        for i, d in enumerate(APERTURE))
        body = '<g class="rot">%s</g>' % inner
    elif opt == 'bore':
        r = 30 if static else 0
        body = ('<mask id="%s"><rect width="100" height="100" fill="#fff"/>'
                '<circle class="punch" cx="50" cy="50" r="%d" fill="#000"/></mask>'
                '<circle class="wave" cx="50" cy="50" r="44" fill="none" '
                'stroke-width="6" opacity="0"/>'
                '<circle class="disc" cx="50" cy="50" r="44" mask="url(#%s)"/>'
                % (u, r, u))
    elif opt == 'lathe':
        body = ('<g class="spin"><path class="body" fill-rule="evenodd" d="%s"/>'
                '<path class="spec" d="M50 6A44 44 0 0 1 94 50L83 50A33 33 0 0 0 50 17Z" '
                'opacity="0"/></g>' % CONTRAST_D)
    elif opt == 'trace':
        body = ('<circle class="trk" cx="50" cy="50" r="37" fill="none" '
                'stroke-width="14"/>')
    elif opt == 'orbit':
        body = ('<circle class="trk" cx="50" cy="50" r="37" fill="none" '
                'stroke-width="14"/>'
                '<g class="orb"><circle class="bead" cx="76.16" cy="23.84" r="9.5"/></g>')
